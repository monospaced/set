#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

/**
 * Writes `src/toolchain.mjs` from the monorepo's toolchain: the Node and pnpm
 * versions the CLI stamps into generated projects, and the ranges of the
 * tooling it installs, read from the pnpm catalog (root devDependencies for
 * anything not catalogued). One place to upgrade, and a scaffold gets the
 * versions this repository develops with. `verify.mjs` fails CI on drift.
 */

/** Tooling installed into every generated project. */
const TOOLING = [
  "@types/node",
  "husky",
  "lint-staged",
  "prettier",
  "vite",
  "vitest",
];

/** What the React variant adds: runtime, then tooling. */
const REACT = {
  dependencies: ["react", "react-dom"],
  devDependencies: [
    "@types/react",
    "@types/react-dom",
    "@vitejs/plugin-react",
    "jsdom",
  ],
};

/** The `catalog:` block of pnpm-workspace.yaml, as name to range. */
function readCatalog() {
  const lines = readFileSync(root("pnpm-workspace.yaml"), "utf8").split("\n");
  const start = lines.indexOf("catalog:");
  const entries = [];
  for (const line of lines.slice(start + 1)) {
    const match = /^ {2}"?([^":]+)"?: (.+)$/.exec(line);
    if (!match) break;
    entries.push([match[1], match[2]]);
  }
  return Object.fromEntries(entries);
}

const root = (path) =>
  fileURLToPath(new URL(`../../../${path}`, import.meta.url));

export const TOOLCHAIN = fileURLToPath(
  new URL("../src/toolchain.mjs", import.meta.url),
);

export async function render() {
  const nodeVersion = readFileSync(root(".node-version"), "utf8").trim();
  const { devDependencies, packageManager } = JSON.parse(
    readFileSync(root("package.json"), "utf8"),
  );
  const pnpmVersion = packageManager.replace(/^pnpm@/, "").split("+")[0];
  const catalog = readCatalog();
  const ranges = (names) =>
    Object.fromEntries(
      names.map((name) => {
        const range = catalog[name] ?? devDependencies[name];
        if (!range || range === "catalog:") {
          throw new Error(
            `${name} is neither in the catalog nor a root devDependency`,
          );
        }
        return [name, range];
      }),
    );
  const tooling = ranges(TOOLING);
  const react = {
    dependencies: ranges(REACT.dependencies),
    devDependencies: ranges(REACT.devDependencies),
  };

  const source = `// Generated by scripts/sync.mjs from the monorepo toolchain. Do not edit.

/** Node major written to \`engines\` and \`.node-version\`. */
export const NODE_MAJOR = ${Number(nodeVersion)};

/** pnpm version written to \`packageManager\`; \`engines\` takes its major. */
export const PNPM_VERSION = "${pnpmVersion}";

/** Tooling installed into every project, at the monorepo's ranges. */
export const TOOLING = ${JSON.stringify(tooling)};

/** What the React variant adds, at the monorepo's ranges. */
export const REACT = ${JSON.stringify(react)};
`;

  // The pre-commit hook would format it anyway; match that so verify agrees.
  return prettier.format(source, { filepath: TOOLCHAIN });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TOOLCHAIN, await render());
  console.log("packages/create/src/toolchain.mjs written.");
}
