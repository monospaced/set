#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

/**
 * Writes the stepper example from `templates/stepper.md` and the playground's
 * stepper source, so the code an agent copies is code that builds, type-checks
 * and passes lint. `verify.mjs` fails CI on drift.
 */

const here = (path) => fileURLToPath(new URL(path, import.meta.url));

export const EXAMPLE = here("../src/set-strict/examples/stepper.md");

const TEMPLATE = here("../templates/stepper.md");

/**
 * The source file that replaces each placeholder in the template. The
 * placeholder `<!-- css -->` becomes a ```css code block holding Stepper.css,
 * and `<!-- tsx -->` a ```tsx block holding Stepper.tsx.
 */
const SOURCES = {
  css: here("../../../apps/playground/src/stepper/Stepper.css"),
  tsx: here("../../../apps/playground/src/stepper/Stepper.tsx"),
};

export async function render() {
  let markdown = readFileSync(TEMPLATE, "utf8");

  for (const [lang, path] of Object.entries(SOURCES)) {
    const placeholder = `<!-- ${lang} -->`;
    if (!markdown.includes(placeholder)) {
      throw new Error(`templates/stepper.md has no ${placeholder} placeholder`);
    }
    const code = readFileSync(path, "utf8").trimEnd();
    markdown = markdown.replace(
      placeholder,
      () => `\`\`\`${lang}\n${code}\n\`\`\``,
    );
  }

  const source = `<!-- Generated by scripts/sync.mjs from templates/stepper.md and apps/playground/src/stepper. Do not edit. -->

${markdown}`;

  return prettier.format(source, { filepath: EXAMPLE });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(EXAMPLE, await render());
  console.log("packages/skills/src/set-strict/examples/stepper.md written.");
}
